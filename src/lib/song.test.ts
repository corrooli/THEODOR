import { describe, expect, test } from 'vitest';
import { DEMO_SONGS, decodeSeed, encodeSeed, normalizeSong, songFromJSON, songFromText, songToJSON } from './song';

describe('song format', () => {
  test('demo songs parse', () => {
    for (const d of DEMO_SONGS) expect(songFromText(d.title, d.text, d.tempo).sections.length).toBeGreaterThan(0);
  });

  test('JSON round trip', () => {
    const s = songFromText('Test', 'Verse: Dm7 G7 Cmaj7*8 | Chorus: D/F# Bb', 110);
    s.key = { tonic: 0, mode: 'major' };
    const back = songFromJSON(songToJSON(s));
    expect(back).toEqual(s);
  });

  test('seed link round trip is compact', async () => {
    const s = songFromText('Autumn', DEMO_SONGS[0].text, 120);
    const seed = await encodeSeed(s);
    expect(seed).toMatch(/^1\.[A-Za-z0-9_-]+$/);
    expect(seed.length).toBeLessThan(400);
    const back = await decodeSeed(seed);
    expect(back.title).toBe('Autumn');
    expect(back.sections.map(x => x.chords.map(c => [c.ref, c.beats])))
      .toEqual(s.sections.map(x => x.chords.map(c => [c.ref, c.beats])));
  });

  test('preserves slash bass and spelling preference', async () => {
    const s = songFromText('Slash', 'A: D/F# Gbmaj7 C', 90);
    const back = await decodeSeed(await encodeSeed(s));
    expect(back.sections[0].chords.map(c => c.ref)).toEqual(s.sections[0].chords.map(c => c.ref));
  });

  // Frozen v1 link: must keep opening in every future version.
  test('frozen v1 seed keeps working', async () => {
    // Generated by THEODOR 0.1 — DO NOT regenerate. If this breaks, add a migration instead.
    const frozen = '1.izbUUXIryq9KzVPSsTTSMdCJjlZyVAKSBjpKSjomsTrR5jCGpY5SLoRlChGKBTKVnECKjYBS5nDlUBbQhNzELCDHAsgxAmvRMQMyzWDiJjq6QNuTlGJBAAA';
    const back = await decodeSeed(frozen);
    expect(back.title).toBe('Frozen');
    expect(back.tempo).toBe(92);
    expect(back.sections.map(s => s.name)).toEqual(['A', 'B']);
    expect(back.sections[1].chords.map(c => c.ref)).toEqual([
      { root: 2, q: 'm7' }, { root: 7, q: '7' }, { root: 0, q: 'maj7' }, { root: 2, q: '', bass: 6, pref: undefined }, { root: 6, q: 'maj7', pref: 'flat' },
    ].map(r => JSON.parse(JSON.stringify(r))));
    expect(back.sections[1].chords[2].beats).toBe(8);
  });

  test('rejects garbage and future versions politely', async () => {
    await expect(decodeSeed('nope')).rejects.toThrow();
    expect(() => normalizeSong({ v: 999 })).toThrow(/newer THEODOR/);
    const cleaned = normalizeSong({ title: 'x', sections: [{ name: 'A', chords: [{ ref: { root: 99, q: 'm7' } }, { ref: { root: 2, q: 'bogus' } }, { ref: { root: 2, q: 'm7' }, beats: 999 }] }] });
    expect(cleaned.sections[0].chords).toHaveLength(1);
    expect(cleaned.sections[0].chords[0].beats).toBe(32);
  });
});
